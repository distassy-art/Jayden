export function searchKb(query, overrides) {
  const list = allProducts(overrides);
  const ts = tokens(query);
  const qn = norm(query);
  if (!qn.trim()) return [];
  const scores = new Map(list.map((p) => [p.sku, 0]));
  for (const { re, boost } of INTENT) {
    if (re.test(query)) for (const sku of boost) scores.set(sku, (scores.get(sku) || 0) + 8);
  }
  for (const p of list) {
    const hay = norm(
      [p.sku, p.category, p.nameAr, p.nameEn, p.descAr, p.descEn, ...(p.keywords || []), ...(p.faq || []).flatMap((f) => [f.qAr, f.aAr, f.qEn, f.aEn])].join(" "),
    );
    let s = scores.get(p.sku) || 0;
    if (hay.includes(qn) && qn.length > 4) s += 12;
    for (const t of ts) {
      if (hay.includes(t)) s += t.length > 4 ? 3 : 2;
      if (norm(p.sku) === t) s += 10;
    }
    scores.set(p.sku, s);
  }
  return list
    .map((p) => ({ ...p, score: scores.get(p.sku) || 0 }))
    .filter((p) => p.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 3);
}

export function bySku(sku, overrides) {
  return allProducts(overrides).find((p) => p.sku === sku);
}

export function byPage(path, overrides) {
  const bare = String(path || "").replace(/^\/en/, "") || "/";
  return allProducts(overrides).filter((p) => p.page === bare || p.page === path);
}

export async function webFallback(query) {
  const q = `${query} queue kiosk nurse call Egypt`;
  try {
    const url = `https://api.duckduckgo.com/?q=${encodeURIComponent(q)}&format=json&no_html=1&skip_disambig=1`;
    const res = await fetch(url, { headers: { accept: "application/json" } });
    if (!res.ok) return "";
    const j = await res.json();
    const bits = [];
    if (j.AbstractText) bits.push(j.AbstractText);
    if (j.Heading) bits.push(j.Heading);
    for (const t of j.RelatedTopics || []) {
      if (t.Text) bits.push(t.Text);
      if (Array.isArray(t.Topics)) for (const x of t.Topics.slice(0, 2)) if (x.Text) bits.push(x.Text);
    }
    return bits.join("\n").slice(0, 1200);
  } catch {
    return "";
  }
}
