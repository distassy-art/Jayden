function sellOf(buy) {
  return Number((Number(buy) * 2).toFixed(4));
}

function enrichCatalog(item) {
  const sellUsd = sellOf(item.buyUsd);
  const priceRule = item.priceRule || "catalog-2x";
  return {
    ...item,
    priceRule,
    sellUsd,
    marginPct: 100,
    faq: item.faq || CATALOG_FAQ(item.nameAr, item.nameEn, sellUsd, item.unitAr, item.unitEn, item.moq),
  };
}

export function allProducts(overrides = {}) {
  const extras = PRODUCTS.map((p) => ({ ...p, sellUsd: p.sellUsd ?? null, buyUsd: p.buyUsd ?? null }));
  const catalog = CATALOG_SEED.map(enrichCatalog);
  const merged = [...extras, ...catalog].map((p) => {
    const o = overrides[p.sku];
    return o ? { ...p, ...o, sku: p.sku, faq: o.faq || p.faq } : p;
  });
  return merged;
}

export function catalogItems(overrides) {
  return allProducts(overrides).filter((p) => p.buyUsd != null);
}

export function publicProducts(overrides) {
  return allProducts(overrides).map((p) => ({
    sku: p.sku,
    category: p.category,
    priceRule: p.priceRule,
    nameAr: p.nameAr,
    nameEn: p.nameEn,
    descAr: p.descAr,
    descEn: p.descEn,
    page: p.page,
    sellUsd: p.priceRule === "catalog-2x" ? p.sellUsd : null,
    unitAr: p.unitAr || (p.priceRule === "quote" ? "بند" : "قطعة"),
    unitEn: p.unitEn || (p.priceRule === "quote" ? "line" : "pc"),
    faq: p.faq,
    keywords: p.keywords || [],
  }));
}

function norm(s) {
  return String(s || "")
    .toLowerCase()
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/[^\p{L}\p{N}\s×x-]/gu, " ");
}

function tokens(q) {
  return norm(q)
    .split(/\s+/)
    .filter((t) => t.length >= 2);
}

